import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for wallet transactions
const initialState = {
  balance: 0,
  transactions: [],
  // Add other wallet-related properties as needed
};

// Create the transaction slice
const transactionSlice = createSlice({
  name: 'transaction',
  initialState,
  reducers: {
    setBalance: (state, action) => {
      state.balance = action.payload;
    },
    addTransaction: (state, action) => {
      state.transactions.push(action.payload);
    },
    // Add other reducer actions as needed for wallet transactions
  },
});

// Export the action creators generated by createSlice
export const { setBalance, addTransaction } = transactionSlice.actions;

// Export the transaction reducer
export default transactionSlice.reducer;
