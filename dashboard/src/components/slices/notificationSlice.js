import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for notifications
const initialState = {
  notifications: [],
  // Add other notification-related properties as needed
};

// Create the notification slice
const notificationSlice = createSlice({
  name: 'notification',
  initialState,
  reducers: {
    addNotification: (state, action) => {
      state.notifications.push(action.payload);
    },
    removeNotification: (state, action) => {
      state.notifications = state.notifications.filter(
        (notification) => notification.id !== action.payload
      );
    },
    clearNotifications: (state) => {
      state.notifications = [];
    },
    // Add other reducer actions as needed for notification management
  },
});

// Export the action creators generated by createSlice
export const { addNotification, removeNotification, clearNotifications } = notificationSlice.actions;

// Export the notification reducer
export default notificationSlice.reducer;
