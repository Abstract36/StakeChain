import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for integration status
const initialState = {
  isIntegrated: false,
  integrationService: null,
  // Add other integration-related properties as needed
};

// Create the integration slice
const integrationSlice = createSlice({
  name: 'integration',
  initialState,
  reducers: {
    setIntegration: (state, action) => {
      state.isIntegrated = true;
      state.integrationService = action.payload;
    },
    removeIntegration: (state) => {
      state.isIntegrated = false;
      state.integrationService = null;
    },
    // Add other reducer actions as needed for integration management
  },
});

// Export the action creators generated by createSlice
export const { setIntegration, removeIntegration } = integrationSlice.actions;

// Export the integration reducer
export default integrationSlice.reducer;
