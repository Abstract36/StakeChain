import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for the blockchain connection status
const initialState = {
  isConnected: false,
  blockchainProvider: null,
  // Add other blockchain-related properties as needed
};

// Create the blockchain connection slice
const blockchainConnectionSlice = createSlice({
  name: 'blockchainConnection',
  initialState,
  reducers: {
    connectToBlockchain: (state, action) => {
      state.isConnected = true;
      state.blockchainProvider = action.payload;
    },
    disconnectFromBlockchain: (state) => {
      state.isConnected = false;
      state.blockchainProvider = null;
    },
    // Add other reducer actions as needed
  },
});

// Export the action creators generated by createSlice
export const { connectToBlockchain, disconnectFromBlockchain } = blockchainConnectionSlice.actions;

// Export the blockchain connection reducer
export default blockchainConnectionSlice.reducer;
