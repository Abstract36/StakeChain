import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for token data
const initialState = {
  tokens: [],
  // Add other token-related properties as needed
};

// Create the token slice
const tokenSlice = createSlice({
  name: 'token',
  initialState,
  reducers: {
    addToken: (state, action) => {
      state.tokens.push(action.payload);
    },
    removeToken: (state, action) => {
      state.tokens = state.tokens.filter((token) => token.id !== action.payload);
    },
    // Add other reducer actions as needed for token management
  },
});

// Export the action creators generated by createSlice
export const { addToken, removeToken } = tokenSlice.actions;

// Export the token reducer
export default tokenSlice.reducer;
