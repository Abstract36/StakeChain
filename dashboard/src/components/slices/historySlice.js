import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for navigation history
const initialState = {
  history: [],
  // Add other history-related properties as needed
};

// Create the history slice
const historySlice = createSlice({
  name: 'history',
  initialState,
  reducers: {
    pushToHistory: (state, action) => {
      state.history = [...state.history, action.payload];
    },
    popFromHistory: (state) => {
      const updatedHistory = [...state.history];
      updatedHistory.pop();
      state.history = updatedHistory;
    },
    // Add other reducer actions as needed for history management
  },
});

// Export the action creators generated by createSlice
export const { pushToHistory, popFromHistory } = historySlice.actions;

// Export the history reducer
export default historySlice.reducer;
