import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for the wallet
const initialState = {
  balance: 0,
  transactions: [],
  settings: {
    currency: 'USD',
    language: 'en',
    // Add other wallet settings as needed
  },
  // Add other wallet-related properties as needed
};

// Create the wallet slice
const walletSlice = createSlice({
  name: 'wallet',
  initialState,
  reducers: {
    setBalance: (state, action) => {
      state.balance = action.payload;
    },
    addTransaction: (state, action) => {
      state.transactions.push(action.payload);
    },
    setWalletSettings: (state, action) => {
      state.settings = {
        ...state.settings,
        ...action.payload,
      };
    },
    // Add other reducer actions as needed for wallet-related actions
  },
});

// Export the action creators generated by createSlice
export const { setBalance, addTransaction, setWalletSettings } = walletSlice.actions;

// Export the wallet reducer
export default walletSlice.reducer;
