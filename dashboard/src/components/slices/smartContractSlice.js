import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for smart contracts
const initialState = {
  contracts: [],
  // Add other smart contract-related properties as needed
};

// Create the smart contract slice
const smartContractSlice = createSlice({
  name: 'smartContract',
  initialState,
  reducers: {
    removeContract: (state, action) => {
      // Assuming action.payload is the contract ID to remove
      state.contracts = state.contracts.filter(
        (contract) => contract.id !== action.payload
      );
    },
    // Add other reducer actions as needed for smart contracts
  },
});

// Export the action creators generated by createSlice
export const { removeContract } = smartContractSlice.actions;

// Export the smart contract reducer
export default smartContractSlice.reducer;
