import { createSlice } from '@reduxjs/toolkit';

// Define the initial state for security settings
const initialState = {
  theme: 'light',
  language: 'en',
  // Add other security-related properties as needed
};

// Create the security slice
const securitySlice = createSlice({
  name: 'security',
  initialState,
  reducers: {
    setTheme: (state, action) => {
      state.theme = action.payload;
    },
    setLanguage: (state, action) => {
      state.language = action.payload;
    },
    // Add other reducer actions as needed for security settings
  },
});

// Export the action creators generated by createSlice
export const { setTheme, setLanguage } = securitySlice.actions;

// Export the security reducer
export default securitySlice.reducer;
